// ---- Bulk generator for other cases ----
function genPersons(caseId: string, count: number, seed: number, riskPool: PersonEntity['riskLevel'][]): PersonEntity[] {
  const rand = mulberry32(seed);
  const out: PersonEntity[] = [];
  for (let i = 0; i < count; i++) {
    const male = rand() > 0.4;
    const first = male ? pick(rand, FIRST_NAMES_M) : pick(rand, FIRST_NAMES_F);
    const last = pick(rand, LAST_NAMES);
    const id = `P-${caseId.slice(-3).toUpperCase()}-${String(i + 1).padStart(3, '0')}`;
    out.push({
      id,
      caseIds: [caseId],
      type: 'person',
      name: `${first} ${last}`,
      label: i === 0 ? 'PRIMARY SUBJECT' : 'ASSOCIATE',
      status: rand() > 0.15 ? 'active' : 'unknown',
      riskLevel: pick(rand, riskPool),
      confidence: 0.6 + rand() * 0.39,
      metadata: {
        dateOfBirth: `19${randInt(rand, 70, 99)}-0${randInt(rand, 1, 9)}-${randInt(rand, 10, 27)}`,
        aliases: [],
        nationality: 'Indian',
        occupation: pick(rand, ['Trader', 'Broker', 'Clerk', 'Transporter', 'Agent', 'Consultant']),
        gender: male ? 'male' : 'female',
        identityConfidence: 0.6 + rand() * 0.39,
        address: pick(rand, ['Mumbai', 'Pune', 'Nashik', 'Thane', 'Surat']),
        idNumber: `XXXX-XXXX-${randInt(rand, 1000, 9999)}`,
      },
      sourceIds: [`src-gen-${caseId}`],
      createdAt: '2026-05-01T09:00:00.000Z',
      updatedAt: '2026-09-01T09:00:00.000Z',
    });
  }
  return out;
}

